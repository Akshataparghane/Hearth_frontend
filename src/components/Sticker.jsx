export const stickerIds = stickers.map((item) => item.id);

export function stickerLabel(id) {
  return stickers.find((item) => item.id === id)?.label || 'Sticker';
}

export function Sticker({ id, small = false }) {
  if (!stickerIds.includes(id)) return null;
  return (
    <img
      className={small ? 'sticker sm' : 'sticker'}
      src={`/stickers/${id}.png`}
      alt={stickerLabel(id)}
    />
  );
}
